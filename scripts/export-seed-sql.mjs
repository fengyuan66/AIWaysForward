// Writes supabase/seed.sql from the bundled content, so the database starts out identical to the static site.
// Run: npm run seed:sql   (then paste supabase/seed.sql into the Supabase SQL editor, after schema.sql)
// Ids are derived from the content, so running the seed twice does nothing the second time.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { pathToFileURL } from 'node:url';

const load = (f) => import(pathToFileURL(path.resolve(f)).href);
const { news } = await load('src/content/news.js');
const { pastEvents } = await load('src/content/career.js');
const { segmentsToText } = await load('src/lib/format.js');

const sql = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const uuid = (seed) => {
  const h = crypto.createHash('sha1').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
// 'Aug 21st 2026' → '2026-08-21'
const iso = (label) => {
  const [mon, day, year] = label.replace(/(\d+)(st|nd|rd|th)/, '$1').split(' ');
  const m = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'].indexOf(mon) + 1;
  return `${year}-${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
};

const out = [];
out.push('-- Generated by `npm run seed:sql` from src/content/*.js — do not edit by hand.');
out.push('-- Run after schema.sql. Safe to run twice.');
out.push('');
out.push('insert into public.articles (id, position, source, author, author_href, published_on, title, href, image_url) values');
out.push(
  news.items
    .map((a, i) => {
      const author = a.authors[0];
      // two original author links pointed at the wrong person; they stay unlinked (see docs/TBD_REGISTER.md)
      const href = author?.suspect ? null : author?.href;
      return `  (${[sql(uuid(a.href)), i + 1, sql(a.source), sql(author?.text ?? ''), sql(href), sql(iso(a.date)), sql(a.title), sql(a.href), sql(a.image)].join(', ')})`;
    })
    .join(',\n'),
);
out.push('on conflict (id) do nothing;');
out.push('');
out.push("insert into public.events (id, status, speaker_name, talk, when_text, event_date, bio, note, photo_url, join_url) values");
out.push(
  pastEvents
    .map((e) =>
      `  (${[
        sql(uuid(e.id)),
        sql('past'),
        sql(e.name),
        sql(e.talk),
        sql(e.when),
        sql(e.date),
        sql(e.bio.map(segmentsToText).join('\n\n')),
        sql(segmentsToText(e.note)),
        sql(e.photo),
        'null',
      ].join(', ')})`,
    )
    .join(',\n'),
);
out.push('on conflict (id) do nothing;');
out.push('');

fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/seed.sql', out.join('\n'));
console.log(`supabase/seed.sql — ${news.items.length} articles, ${pastEvents.length} past event(s)`);
